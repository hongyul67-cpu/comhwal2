function render(s) {
  if (!s) return '';
  var body = '';
  if (s.type === 'svg') body = s.svg || '';
  else if (s.type === 'table') {
    body = '<table class="cw"><thead><tr>' +
      (s.head || []).map(function (h) { return '<th>' + h + '</th>'; }).join('') +
      '</tr></thead><tbody>' +
      (s.rows || []).map(function (r) {
        return '<tr>' + r.map(function (c) { return '<td>' + c + '</td>'; }).join('') + '</tr>';
      }).join('') + '</tbody></table>';
  }
  return '<div class="cwfig">' + body + (s.cap ? '<div class="cwcap">' + s.cap + '</div>' : '') + '</div>';
}

